import { ConsoleLogger, type LoggerService } from '@nestjs/common';

/** Fail closed: arbitrary messages, context, metadata and stack traces are untrusted. */
export class SafeLogger implements LoggerService {
  private readonly sink = new ConsoleLogger('CoreApi', {
    json: true, colors: false,
    logLevels: ['log', 'error', 'warn', 'debug', 'verbose', 'fatal'],
  });

  log(_message: unknown, ..._params: unknown[]): void { this.sink.log('REDACTED_LOG'); }
  error(_message: unknown, ..._params: unknown[]): void { this.sink.error('REDACTED_LOG'); }
  warn(_message: unknown, ..._params: unknown[]): void { this.sink.warn('REDACTED_LOG'); }
  debug(_message: unknown, ..._params: unknown[]): void { this.sink.debug('REDACTED_LOG'); }
  verbose(_message: unknown, ..._params: unknown[]): void { this.sink.verbose('REDACTED_LOG'); }
  fatal(_message: unknown, ..._params: unknown[]): void { this.sink.fatal('REDACTED_LOG'); }

  /** Only an address generated by the listener; never interpolate general log inputs. */
  listening(address: string): void {
    try {
      const url = new URL(address);
      if (url.protocol === 'http:' && ['127.0.0.1', '[::1]', 'localhost'].includes(url.hostname) &&
          url.port && !url.username && !url.password && !url.search && !url.hash && url.pathname === '/') {
        this.sink.log(`Listening on http://${url.hostname}:${url.port}`);
        return;
      }
    } catch { /* Do not echo invalid addresses. */ }
    this.sink.log('SERVICE_LISTENING');
  }
}
